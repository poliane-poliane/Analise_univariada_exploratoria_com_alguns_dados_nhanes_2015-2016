"""Nota sobre causalidade, confundimento e efeito de coorte:
Um dos papéis mais importantes da estatística não é apenas mostrar que existem diferenças entre grupos, mas ajudar os pesquisadores a descobrir as verdadeiras causas por trás dessas diferenças, evitando interpretações enganosas.
Na análise anterior, observamos que tanto a pressão arterial quanto o nível de escolaridade variam de acordo com a idade. No entanto, a relação de causa e efeito é completamente diferente nos dois casos:

• Causalidade direta (Pressão arterial): É perfeitamente plausível que o envelhecimento biológico cause diretamente o aumento da pressão arterial (devido ao enrijecimento natural dos vasos sanguíneos ao longo dos anos, por exemplo).

• Fator de confundimento e Efeito de Coorte (Escolaridade): Seria um erro concluir que "envelhecer faz a escolaridade diminuir". Aqui, a idade atua como um fator de confundimento — uma variável que parece ser a causa, mas que, na verdade, está apenas ligada ao verdadeiro motivo da diferença: o efeito de coorte de nascimento.

O que é o efeito de coorte de nascimento?

Na estatística e na epidemiologia, uma coorte é um grupo de pessoas que compartilham uma característica em comum — neste caso, terem nascido na mesma época (geração). O efeito de coorte ocorre quando os resultados observados em um grupo são consequência das condições históricas, sociais ou culturais específicas da época em que aquelas pessoas cresceram, e não do processo biológico de envelhecer.

Como isso aparece nos dados da pesquisa (NHANES):

A NHANES é uma pesquisa transversal, o que significa que ela funciona como uma "fotografia": todos os dados de uma etapa são coletados em um único momento no tempo, comparando pessoas de diferentes idades simultaneamente (em vez de acompanhar as mesmas pessoas ao longo de décadas).

• Quem tinha 65 anos em 2015 (ano da coleta) estava na idade de entrar na faculdade por volta de 1970, uma época em que o ensino superior era muito mais restrito e menos acessível.

• Já quem estava na casa dos 20 anos em 2015 chegou à idade universitária por volta de 2010 ou depois, quando o acesso às universidades já havia se expandido enormemente.

Portanto, os mais jovens apresentam hoje um nível de escolaridade maior não porque "ser jovem dá mais estudo", mas porque nasceram em uma geração com muito mais oportunidades educacionais. Como esse efeito está ligado à geração e não à idade biológica, quando esses jovens de 20 anos chegarem aos 65, eles levarão seus diplomas com eles — e o retrato da relação entre idade e escolaridade nas pesquisas futuras será bem diferente do atual.
"""

