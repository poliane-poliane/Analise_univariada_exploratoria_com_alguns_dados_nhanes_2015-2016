"""### Parâmetro observed = False no groupby()

No pandas, o parâmetro observed=False no groupby() serve para controlar como o agrupamento lida com categorias que não aparecem de facto nos dados quando a coluna agrupada é do tipo Categorical (como costuma acontecer com colunas criadas por pd.cut(), tal como 'Idade por faixas').  

O que acontece na prática?

Imagine que criou faixas etárias com pd.cut(), mas na faixa dos 80–90 anos não há nenhum registo no df:observed=False (mantém categorias vazias): o pandas inclui todas as categorias definidas no tipo categórico, mesmo aquelas sem ocorrências (mostrando 0 ou omitindo linhas sem contagem conforme a operação), preservando a estrutura completa das faixas.observed=True (apenas categorias observadas): o pandas considera apenas as categorias que têm pelo menos um registo presente nos dados.

Por que o aviso (FutureWarning) aparecia?

Em versões mais antigas do pandas, o padrão era observed=False (o que em colunas categóricas grandes podia gerar combinações vazias desnecessárias). O pandas avisou que no futuro o padrão passará a ser observed=True, pedindo para explicitar o valor desejado.

Também podemos estratificar conjuntamente por idade e gênero para explorar como o nível de escolaridade varia de acordo com ambos os fatores simultaneamente. Ao fazer isso, fica mais fácil interpretar os resultados se transformarmos os níveis de escolaridade em colunas (tabela dinâmica/pivô) e normalizarmos as contagens para que somem 1. Depois disso, os resultados podem ser interpretados como proporções ou probabilidades. Uma observação notável dessa tabela é que, para pessoas com até cerca de 60 anos, as mulheres têm maior probabilidade de terem concluído o ensino superior do que os homens, mas, para pessoas com mais de 60 anos, essa relação se inverte.

Vamos:

- filtrar a coluna 'Nível de escolaridade' (removendo 'Valores faltantes' e 'Não sabem');

- agrupar por 'Idade por faixas' e 'Gênero';

- contar as ocorrências;

- transformar o resultado numa tabela de proporções.
"""

dx = df.loc[~df['Nível de escolaridade'].isin(['Valores faltantes', 'Não sabem']), :] # eliminando valores faltantes/não sabem
dx = dx.groupby(['Idade por faixas', 'Gênero'], observed = False)['Nível de escolaridade']
dx = dx.value_counts()
dx = dx.unstack()
dx = dx.apply(lambda x: x/x.sum(), axis = 1) # normaliza com cada estrado para obter proporções
print(dx.to_string(float_format = '%.3f'))

